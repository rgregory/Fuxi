import AppKit
import Foundation

/// Builds the shell scripts Fuxi hands to the user and saves them where the user chooses.
/// Fuxi never runs anything as root: the user reads each script and runs it with sudo.
enum ScriptExport {
    private static let rootCheck = """
    if [ "$(id -u)" -ne 0 ]; then
      echo "Run this with sudo: sudo sh \\"$0\\"" >&2
      exit 1
    fi
    """

    private static func header(_ purpose: String, host: String, run name: String) -> String {
        let stamp = ISO8601DateFormatter().string(from: Date())
        return """
        #!/bin/sh
        # Generated by Fuxi on \(stamp) for \(oneLine(host)).
        # \(purpose)
        # Read it first, then run:  sudo sh \(name)
        """
    }

    /// Comments must stay on one line or a newline in a value could start a command.
    private static func oneLine(_ s: String) -> String {
        s.components(separatedBy: .newlines).joined(separator: " ")
    }

    /// `sysctl -w` for each write. Keys and values must already pass Sysctl.isValidKey/isValidValue.
    static func applyScript(_ writes: [KernelWrite], current: [String: String], host: String) -> String {
        var lines = [
            header("Changes \(writes.count) kernel setting(s). They last until the next restart.",
                   host: host, run: "fuxi-apply.sh"),
            "",
            rootCheck,
            "",
            "status=0",
        ]
        for w in writes where Sysctl.isValidKey(w.key) && Sysctl.isValidValue(w.value) {
            lines.append("")
            lines.append("# \(w.key): \(oneLine(current[w.key] ?? "?")) -> \(w.value)")
            lines.append("\(Sysctl.path) -w \(w.key)=\(w.value) || { echo \"Rejected: \(w.key)\" >&2; status=1; }")
        }
        lines += ["", "exit $status", ""]
        return lines.joined(separator: "\n")
    }

    /// Writes /etc/sysctl.conf, backing up a file Fuxi didn't write, once.
    static func installBootScript(_ config: String, host: String) -> String {
        let p = BootConfig.path, b = BootConfig.backupPath
        return [
            header("Writes \(p) so these settings apply at startup. A \(p) that Fuxi didn't write is backed up once to \(b).",
                   host: host, run: "fuxi-boot-install.sh"),
            "",
            "set -e",
            rootCheck,
            "",
            "if [ -f \(p) ] && [ ! -f \(b) ] && ! /usr/bin/head -1 \(p) | /usr/bin/grep -qF 'Managed by Fuxi'; then",
            "  /bin/cp -p \(p) \(b)",
            "  echo \"Backed up your existing \(p) to \(b)\"",
            "fi",
            "",
            "/bin/cat > \(p).fuxi-new <<'FUXI_EOF'",
            config.hasSuffix("\n") ? String(config.dropLast()) : config,
            "FUXI_EOF",
            "/usr/sbin/chown root:wheel \(p).fuxi-new",
            "/bin/chmod 644 \(p).fuxi-new",
            "/bin/mv \(p).fuxi-new \(p)",
            "echo \"Wrote \(p). Restart, then check At Boot in Fuxi.\"",
            "",
        ].joined(separator: "\n")
    }

    /// Restores the backup, or deletes Fuxi's file. Leaves a file Fuxi didn't write alone.
    static func removeBootScript(host: String) -> String {
        let p = BootConfig.path, b = BootConfig.backupPath
        return [
            header("Removes Fuxi's \(p) and puts back the file it replaced, if any.",
                   host: host, run: "fuxi-boot-remove.sh"),
            "",
            "set -e",
            rootCheck,
            "",
            "if [ -f \(p) ] && ! /usr/bin/head -1 \(p) | /usr/bin/grep -qF 'Managed by Fuxi'; then",
            "  echo \"\(p) wasn't written by Fuxi. Leaving it alone.\" >&2",
            "  exit 1",
            "fi",
            "if [ -f \(b) ]; then",
            "  /bin/mv \(b) \(p)",
            "  echo \"Restored your original \(p)\"",
            "else",
            "  /bin/rm -f \(p)",
            "  echo \"Removed \(p)\"",
            "fi",
            "",
        ].joined(separator: "\n")
    }

    /// Asks where to save the script. Returns nil if the user cancels or the write fails.
    @MainActor
    static func save(_ script: String, suggestedName: String, message: String) -> URL? {
        let panel = NSSavePanel()
        panel.nameFieldStringValue = suggestedName
        panel.message = message
        panel.canCreateDirectories = true
        panel.directoryURL = FileManager.default.urls(for: .downloadsDirectory, in: .userDomainMask).first
        guard panel.runModal() == .OK, let url = panel.url else { return nil }
        do {
            try script.write(to: url, atomically: true, encoding: .utf8)
            try FileManager.default.setAttributes([.posixPermissions: 0o644], ofItemAtPath: url.path)
            return url
        } catch {
            NSAlert(error: error).runModal()
            return nil
        }
    }

    /// The command to run, copied to the clipboard, and what to do next.
    @MainActor
    static func instructions(for url: URL) -> String {
        let quoted = "'" + url.path.replacingOccurrences(of: "'", with: "'\\''") + "'"
        let command = "sudo sh \(quoted)"
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(command, forType: .string)
        return "Saved \(url.lastPathComponent). Read it, then run this in Terminal (it's on the clipboard):\n\n\(command)\n\nFuxi reads the kernel again when you come back."
    }
}
